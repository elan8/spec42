#!/usr/bin/env node
/**
 * Measure the diagram views of the reference models as a document would print them.
 *
 * For every diagram view of every reference model this renders the view with `spec42 diagram`
 * and records its size and the smallest text once the figure is fitted to the text area of an
 * A4 page (165 x 215 mm upright or 245 x 135 mm turned, whichever shows it larger).
 *
 * Reference models:
 *   - each directory under examples/ (the elan8/sysml-examples submodule)
 *   - third_party/sysml-robot-vacuum-cleaner/model (scripts/fetch-robot-vacuum-cleaner.sh)
 *
 * Writes docs/reference/DIAGRAM-MEASUREMENTS.md, so a layout change shows its effect on size
 * and text in the diff. The robot is measured when it has been fetched and its pinned model
 * declares views.
 *
 * With `--model <dir>` (repeatable) only those models are measured and the table is printed,
 * for a model that is not a pinned reference.
 *
 * Usage:
 *   node scripts/measure-diagrams.mjs [--check] [--bin <path to spec42>] [--model <dir>]...
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const binFlag = process.argv.indexOf("--bin");
const exe = process.platform === "win32" ? "spec42.exe" : "spec42";
const bin =
  binFlag >= 0
    ? path.resolve(process.argv[binFlag + 1])
    : [process.env.SPEC42_BIN, `target/release/${exe}`, `target/debug/${exe}`]
        .filter(Boolean)
        .map((candidate) => path.resolve(repoRoot, candidate))
        .find((candidate) => fs.existsSync(candidate));
if (!bin || !fs.existsSync(bin)) {
  throw new Error("No spec42 binary. Build it (`cargo build -p server`) or pass --bin.");
}
const outputPath = path.join(repoRoot, "docs", "reference", "DIAGRAM-MEASUREMENTS.md");

/** Text areas of an A4 page in millimetres: upright and turned. */
const PAGES = [
  [165, 215],
  [245, 135],
];
const POINTS_PER_MM = 72 / 25.4;

const extraModels = process.argv
  .map((arg, index) => (arg === "--model" ? process.argv[index + 1] : null))
  .filter(Boolean)
  .map((dir) => ({ name: path.basename(path.resolve(dir)), dir: path.resolve(dir) }));

function referenceModels() {
  if (extraModels.length > 0) return extraModels;
  const models = [];
  const examples = path.join(repoRoot, "examples");
  for (const entry of fs.readdirSync(examples, { withFileTypes: true })) {
    if (entry.isDirectory() && !entry.name.startsWith(".")) {
      models.push({ name: `examples/${entry.name}`, dir: path.join(examples, entry.name) });
    }
  }
  const robot = path.join(repoRoot, "third_party", "sysml-robot-vacuum-cleaner", "model");
  if (fs.existsSync(robot)) models.push({ name: "robot vacuum cleaner", dir: robot });
  return models.sort((a, b) => a.name.localeCompare(b.name));
}

function spec42(args) {
  return execFileSync(bin, args, { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
}

function measure(svg) {
  const viewBox = /<svg[^>]*\sviewBox="([^"]+)"/.exec(svg);
  if (!viewBox) throw new Error("rendered SVG has no viewBox");
  const [, , width, height] = viewBox[1].split(/[\s,]+/).map(Number);
  const sizes = [...svg.matchAll(/font-size:\s*([0-9.]+)px/g)].map((match) => Number(match[1]));
  const smallestPx = sizes.length > 0 ? Math.min(...sizes) : null;
  const mmPerPx = Math.max(...PAGES.map(([w, h]) => Math.min(w / width, h / height, 25.4 / 96)));
  return {
    width: Math.round(width),
    height: Math.round(height),
    smallestPt: smallestPx === null ? null : smallestPx * mmPerPx * POINTS_PER_MM,
  };
}

const rows = [];
for (const model of referenceModels()) {
  const views = JSON.parse(spec42(["diagram", model.dir, "--format", "json"]));
  views.sort(
    (a, b) => a.qualifiedName.localeCompare(b.qualifiedName) || a.kind.localeCompare(b.kind),
  );
  for (const view of views) {
    const svg = spec42([
      "diagram",
      model.dir,
      "--view",
      view.qualifiedName,
      "--kind",
      view.kind,
      "--document",
      view.document,
    ]);
    rows.push({ model: model.name, view, ...measure(svg) });
  }
}

const lines = [
  "# Diagram measurements",
  "",
  "Generated by `node scripts/measure-diagrams.mjs`; do not edit. Each diagram view of the",
  "reference models as `spec42 diagram` renders it: its size, and its smallest text once the",
  "figure is fitted to the text area of an A4 page (165 × 215 mm upright or 245 × 135 mm turned)",
  "without enlarging it. A layout change shows its effect here.",
  "",
  "| Model | View | Kind | Size (px) | Smallest text |",
  "| --- | --- | --- | --- | ---: |",
  ...rows.map(
    (row) =>
      `| ${row.model} | \`${row.view.qualifiedName}\` | ${row.view.kind} | ${row.width} × ${row.height} | ${
        row.smallestPt === null ? "none" : `${row.smallestPt.toFixed(1)} pt`
      } |`,
  ),
  "",
];
const next = lines.join("\n");
if (extraModels.length > 0) {
  console.log(lines.slice(7).join("\n"));
} else if (check) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== next) {
    console.error(
      "docs/reference/DIAGRAM-MEASUREMENTS.md is out of date. Run `node scripts/measure-diagrams.mjs`.",
    );
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputPath, next, "utf8");
  console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${rows.length} views)`);
}
