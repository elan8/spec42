#!/usr/bin/env node
/**
 * Sync VS Code defaults from config/libraries/*.json.
 *
 * Usage:
 *   node scripts/sync-kpar-libraries-config.mjs
 *   node scripts/sync-kpar-libraries-config.mjs --check
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const repoRoot = process.cwd();
const librariesDir = path.join(repoRoot, "config", "libraries");
const generatedTsPath = path.join(
  repoRoot,
  "vscode",
  "src",
  "generated",
  "kparLibrariesDefaults.ts"
);
const check = process.argv.includes("--check");

function loadLibraries() {
  if (!fs.existsSync(librariesDir)) {
    throw new Error(`Missing ${librariesDir}`);
  }
  const files = fs
    .readdirSync(librariesDir)
    .filter((name) => name.toLowerCase().endsWith(".json"))
    .sort();
  if (files.length === 0) {
    throw new Error(`No JSON configs found in ${librariesDir}`);
  }
  return files.map((fileName) => {
    const configPath = path.join(librariesDir, fileName);
    const config = JSON.parse(fs.readFileSync(configPath, "utf8"));
    const stem = path.basename(fileName, ".json");
    const id = typeof config.id === "string" && config.id.trim() ? config.id : stem;
    for (const key of ["displayName", "version", "repo", "format"]) {
      if (typeof config[key] !== "string" || config[key].trim() === "") {
        throw new Error(`${configPath} must define a non-empty string for "${key}".`);
      }
    }
    if (typeof config.contentPath !== "string") {
      throw new Error(`${configPath} must define "contentPath" as a string.`);
    }
    if (!config.pack || typeof config.pack !== "object") {
      throw new Error(`${configPath} must define a "pack" object.`);
    }
    return {
      id,
      displayName: config.displayName,
      version: config.version,
      repo: config.repo,
      format: config.format,
      artifact: config.artifact ?? "",
      contentPath: config.contentPath,
    };
  });
}

const libraries = loadLibraries();
const generatedTs = `// GENERATED by scripts/sync-kpar-libraries-config.mjs - do not edit.
export type KparLibraryDefaults = {
  id: string;
  displayName: string;
  version: string;
  repo: string;
  format: string;
  artifact: string;
  contentPath: string;
};

export const KPAR_LIBRARIES_DEFAULTS: readonly KparLibraryDefaults[] = ${JSON.stringify(
  libraries,
  null,
  2
)} as const;

export function kparLibraryDefaults(id: string): KparLibraryDefaults | undefined {
  return KPAR_LIBRARIES_DEFAULTS.find((library) => library.id === id);
}
`;

if (check) {
  const currentGenerated = fs.existsSync(generatedTsPath)
    ? fs.readFileSync(generatedTsPath, "utf8")
    : "";
  if (currentGenerated !== generatedTs) {
    throw new Error(
      "vscode/src/generated/kparLibrariesDefaults.ts is out of date. Run `node scripts/sync-kpar-libraries-config.mjs`."
    );
  }
} else {
  fs.mkdirSync(path.dirname(generatedTsPath), { recursive: true });
  fs.writeFileSync(generatedTsPath, generatedTs, "utf8");
  console.log(`Wrote ${path.relative(repoRoot, generatedTsPath)}`);
}
